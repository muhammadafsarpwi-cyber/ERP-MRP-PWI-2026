/* ─────────────────────────────────────────────────────────────────────────────
 * stockSummaryExport.ts — Executive PDF, Print & CSV Exporter for Stock Summary
 * Pakistan Wire Industries (Pvt.) Ltd.
 * Full corporate letterhead, dynamic KPI metrics, tabular formatting & audit sign-off
 * ──────────────────────────────────────────────────────────────────────────── */

import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { formatNumber } from '../../utils/numberFormat';

export interface StockSummaryExportItem {
  id: string;
  itemCode: string;
  itemName: string;
  warehouseName: string;
  onHand: number;
  reserved: number;
  available: number;
  uomCode: string;
  status: 'Critical' | 'Low' | 'Healthy' | string;
}

export interface StockSummaryExportMeta {
  divisionName?: string;
  warehouseName?: string;
  totalCatalogItems: number;
  totalOnHand: number;
  totalReserved: number;
  totalAvailable: number;
  generatedBy?: string;
}

/**
 * Downloads an official CSV file of the Stock Summary Report
 */
export function exportStockSummaryCsv(
  records: StockSummaryExportItem[],
  meta: StockSummaryExportMeta,
): void {
  const todayStr = new Date().toISOString().slice(0, 10);
  const nowTimeStr = new Date().toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });

  const lines: string[] = [];

  // Report Header Metadata
  lines.push(`"PAKISTAN WIRE INDUSTRIES (PVT.) LTD. — STOCK SUMMARY & VALUATION REPORT"`);
  lines.push(`"Generated Date:","${todayStr} ${nowTimeStr}"`);
  lines.push(`"Division:","${meta.divisionName || 'All Divisions'}"`);
  lines.push(`"Warehouse:","${meta.warehouseName || 'All Warehouses'}"`);
  lines.push(`"Generated By:","${meta.generatedBy || 'Factory User'}"`);
  lines.push('');

  // Summary Metrics
  lines.push(`"SUMMARY METRICS"`);
  lines.push(`"Total Catalog Items","${meta.totalCatalogItems}"`);
  lines.push(`"Total Stock On Hand","${meta.totalOnHand}"`);
  lines.push(`"Total Customer Demand (Reserved)","${meta.totalReserved}"`);
  lines.push(`"Total Free Available Stock","${meta.totalAvailable}"`);
  lines.push('');

  // Table Column Headers
  lines.push(
    [
      '"#"',
      '"Item Code"',
      '"Item Name / Description"',
      '"Warehouse"',
      '"On Hand Qty"',
      '"Reserved Qty"',
      '"Available Qty"',
      '"UOM"',
      '"Stock Status"',
    ].join(','),
  );

  // Table Rows
  records.forEach((r, idx) => {
    const isNipple = r.itemCode.startsWith('FG-NP');
    const uomDisplay = isNipple ? 'GRS (144 PCS)' : r.uomCode;
    lines.push(
      [
        `"${idx + 1}"`,
        `"${r.itemCode.replace(/"/g, '""')}"`,
        `"${(r.itemName || '').replace(/"/g, '""')}"`,
        `"${(r.warehouseName || '').replace(/"/g, '""')}"`,
        `"${r.onHand}"`,
        `"${r.reserved}"`,
        `"${r.available}"`,
        `"${uomDisplay}"`,
        `"${r.status}"`,
      ].join(','),
    );
  });

  // Totals Row
  lines.push('');
  lines.push(
    [
      '""',
      '"TOTAL"',
      '""',
      '""',
      `"${meta.totalOnHand}"`,
      `"${meta.totalReserved}"`,
      `"${meta.totalAvailable}"`,
      '""',
      '""',
    ].join(','),
  );

  // Trigger UTF-8 Download
  const blob = new Blob(['\uFEFF' + lines.join('\r\n')], {
    type: 'text/csv;charset=utf-8;',
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  const divSafe = (meta.divisionName || 'All-Divisions').replace(/[^a-zA-Z0-9_-]/g, '_');
  link.setAttribute('download', `PWI_Stock_Summary_Report_${divSafe}_${todayStr}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Generates an executive corporate A4 Landscape PDF for Stock Summary & Availability Report,
 * or sends it directly to the browser Print Dialog.
 */
export function exportStockSummaryPdf(
  records: StockSummaryExportItem[],
  meta: StockSummaryExportMeta,
  action: 'pdf' | 'print' = 'pdf',
): void {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const todayStr = new Date().toISOString().slice(0, 10);
  const nowTimeStr = new Date().toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });

  // 1. Corporate Header Banner (Midnight Slate)
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 56, 'F');

  // Brand Name
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('PAKISTAN WIRE INDUSTRIES (PVT.) LTD.', 24, 24);

  // Subtitle
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text('CENTRAL INVENTORY STOCK SUMMARY & AVAILABILITY AUDIT REPORT', 24, 42);

  // Top Right Metadata
  doc.setFontSize(8);
  doc.setTextColor(226, 232, 240);
  doc.text(`Generated: ${todayStr} ${nowTimeStr}`, pageWidth - 24, 20, { align: 'right' });
  doc.text(`Division: ${meta.divisionName || 'All Divisions'}`, pageWidth - 24, 32, { align: 'right' });
  doc.text(`Warehouse: ${meta.warehouseName || 'All Warehouses'}`, pageWidth - 24, 44, { align: 'right' });

  // 2. Executive 4-KPI Summary Cards
  const kpiTop = 68;
  const kpiHeight = 44;
  const kpiGap = 12;
  const marginX = 24;
  const cardCount = 4;
  const cardWidth = (pageWidth - marginX * 2 - kpiGap * (cardCount - 1)) / cardCount;

  const kpis = [
    {
      title: 'TOTAL CATALOG ITEMS',
      value: `${formatNumber(meta.totalCatalogItems, 0)} Items`,
      sub: 'Unique Stock Skus',
      color: [14, 165, 233], // sky-500
      bg: [240, 249, 255],
    },
    {
      title: 'PHYSICAL STOCK ON HAND',
      value: `${formatNumber(meta.totalOnHand, 0)} PCS`,
      sub: 'Verified Ledger Inventory',
      color: [99, 102, 241], // indigo-500
      bg: [238, 242, 255],
    },
    {
      title: 'RESERVED / SALES DEMAND',
      value: `${formatNumber(meta.totalReserved, 0)} PCS`,
      sub: 'Confirmed Open SOC Demand',
      color: [217, 119, 6], // amber-600
      bg: [255, 251, 235],
    },
    {
      title: 'FREE AVAILABLE STOCK',
      value: `${formatNumber(meta.totalAvailable, 0)} PCS`,
      sub: 'Net Allocatable to New Orders',
      color: [22, 163, 74], // emerald-600
      bg: [240, 253, 244],
    },
  ];

  kpis.forEach((kpi, idx) => {
    const x = marginX + idx * (cardWidth + kpiGap);
    // Card background
    doc.setFillColor(kpi.bg[0], kpi.bg[1], kpi.bg[2]);
    doc.setDrawColor(kpi.color[0], kpi.color[1], kpi.color[2]);
    doc.setLineWidth(0.75);
    doc.roundedRect(x, kpiTop, cardWidth, kpiHeight, 3, 3, 'FD');

    // Accent line on left
    doc.setFillColor(kpi.color[0], kpi.color[1], kpi.color[2]);
    doc.rect(x, kpiTop, 3.5, kpiHeight, 'F');

    // Title
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139); // slate-500
    doc.text(kpi.title, x + 8, kpiTop + 13);

    // Value
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(kpi.color[0], kpi.color[1], kpi.color[2]);
    doc.text(kpi.value, x + 8, kpiTop + 27);

    // Subtext
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text(kpi.sub, x + 8, kpiTop + 38);
  });

  // 3. Tabular Data (AutoTable)
  const head = [
    [
      '#',
      'Item Code',
      'Item Name / Description',
      'Warehouse',
      'On Hand Qty',
      'Reserved Qty',
      'Available Qty',
      'UOM',
      'Stock Status',
    ],
  ];

  const body = records.map((r, i) => {
    const isNipple = r.itemCode.startsWith('FG-NP');
    const uomDisplay = isNipple ? 'GRS (144 PCS)' : r.uomCode;

    const onHandFmt = isNipple && r.onHand >= 144
      ? `${formatNumber(r.onHand / 144, 1)} GRS (${formatNumber(r.onHand, 0)})`
      : formatNumber(r.onHand, 0);

    const resFmt = isNipple && r.reserved >= 144
      ? `${formatNumber(r.reserved / 144, 1)} GRS (${formatNumber(r.reserved, 0)})`
      : formatNumber(r.reserved, 0);

    const availFmt = isNipple && r.available >= 144
      ? `${formatNumber(r.available / 144, 1)} GRS (${formatNumber(r.available, 0)})`
      : formatNumber(r.available, 0);

    return [
      String(i + 1),
      r.itemCode,
      r.itemName || '—',
      r.warehouseName || '—',
      onHandFmt,
      resFmt,
      availFmt,
      uomDisplay,
      r.status,
    ];
  });

  // Footer Totals Row
  const foot = [
    [
      '',
      'GRAND TOTAL',
      `${records.length} Consolidated Items`,
      '',
      `${formatNumber(meta.totalOnHand, 0)} PCS`,
      `${formatNumber(meta.totalReserved, 0)} PCS`,
      `${formatNumber(meta.totalAvailable, 0)} PCS`,
      '',
      '',
    ],
  ];

  autoTable(doc, {
    startY: kpiTop + kpiHeight + 12,
    margin: { left: marginX, right: marginX, bottom: 50 },
    head,
    body,
    foot,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59], // slate-800
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: 'bold',
      halign: 'left',
      cellPadding: 4,
    },
    bodyStyles: {
      fontSize: 7.5,
      textColor: [30, 41, 59],
      cellPadding: 3.5,
    },
    footStyles: {
      fillColor: [241, 245, 249],
      textColor: [15, 23, 42],
      fontSize: 8,
      fontStyle: 'bold',
      cellPadding: 4,
    },
    columnStyles: {
      0: { cellWidth: 24, halign: 'center' }, // #
      1: { cellWidth: 100, fontStyle: 'bold' }, // Item Code
      2: { cellWidth: 'auto' }, // Item Name
      3: { cellWidth: 130 }, // Warehouse
      4: { cellWidth: 90, halign: 'right', fontStyle: 'bold' }, // On Hand
      5: { cellWidth: 80, halign: 'right' }, // Reserved
      6: { cellWidth: 80, halign: 'right', fontStyle: 'bold' }, // Available
      7: { cellWidth: 70, halign: 'center' }, // UOM
      8: { cellWidth: 60, halign: 'center', fontStyle: 'bold' }, // Status
    },
    didParseCell: (data) => {
      // Highlight Status column
      if (data.section === 'body' && data.column.index === 8) {
        const text = String(data.cell.raw).trim();
        if (text === 'Critical') {
          data.cell.styles.textColor = [220, 38, 38];
          data.cell.styles.fontStyle = 'bold';
        } else if (text === 'Low') {
          data.cell.styles.textColor = [217, 119, 6];
          data.cell.styles.fontStyle = 'bold';
        } else if (text === 'Healthy') {
          data.cell.styles.textColor = [22, 163, 74];
          data.cell.styles.fontStyle = 'bold';
        }
      }
      // Highlight Reserved column when > 0
      if (data.section === 'body' && data.column.index === 5) {
        const raw = String(data.cell.raw);
        if (raw !== '0' && raw !== '—') {
          data.cell.styles.textColor = [180, 83, 9];
        }
      }
      // Highlight Available column if 0
      if (data.section === 'body' && data.column.index === 6) {
        const raw = String(data.cell.raw);
        if (raw === '0') {
          data.cell.styles.textColor = [220, 38, 38];
        } else {
          data.cell.styles.textColor = [22, 163, 74];
        }
      }
    },
    didDrawPage: (data) => {
      // Page Number Footer
      const str = `Page ${doc.internal.pages.length - 1}`;
      doc.setFontSize(7.5);
      doc.setTextColor(148, 163, 184);
      doc.text(
        `Pakistan Wire Industries (Pvt.) Ltd. · Confidential Enterprise Document · Generated: ${todayStr}`,
        marginX,
        pageHeight - 16,
      );
      doc.text(str, pageWidth - marginX, pageHeight - 16, { align: 'right' });
    },
  });

  // 4. Executive Sign-off Block on the last page
  const finalY = (doc as any).lastAutoTable ? (doc as any).lastAutoTable.finalY + 16 : pageHeight - 65;

  if (finalY + 45 < pageHeight - 20) {
    const sigWidth = (pageWidth - marginX * 2 - 3 * 20) / 4;
    const sigTitles = [
      'Prepared By (Inventory Officer)',
      'Verified By (Store Incharge)',
      'Quality & Production Head',
      'Factory General Manager',
    ];

    sigTitles.forEach((t, i) => {
      const sx = marginX + i * (sigWidth + 20);
      doc.setDrawColor(203, 213, 225); // slate-300
      doc.setLineWidth(0.75);
      doc.line(sx, finalY + 22, sx + sigWidth, finalY + 22);

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7);
      doc.setTextColor(100, 116, 139);
      doc.text(t, sx + sigWidth / 2, finalY + 32, { align: 'center' });
    });
  }

  // 5. Output PDF or Trigger Print
  if (action === 'print') {
    doc.autoPrint();
    const blobUrl = doc.output('bloburl');
    const iframe = document.createElement('iframe');
    iframe.style.position = 'fixed';
    iframe.style.right = '0';
    iframe.style.bottom = '0';
    iframe.style.width = '0';
    iframe.style.height = '0';
    iframe.style.border = '0';
    iframe.src = blobUrl.toString();
    document.body.appendChild(iframe);
    iframe.onload = () => {
      iframe.contentWindow?.focus();
      iframe.contentWindow?.print();
    };
  } else {
    const divSafe = (meta.divisionName || 'All-Divisions').replace(/[^a-zA-Z0-9_-]/g, '_');
    doc.save(`PWI_Stock_Summary_Report_${divSafe}_${todayStr}.pdf`);
  }
}

